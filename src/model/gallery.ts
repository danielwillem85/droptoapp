export function templateBySlug(slug: string | null | undefined): AppTemplate | undefined {
  return TEMPLATES.find((t) => t.slug === slug);
}

/** A template as a project to open in the editor. */
export function templateProject(t: AppTemplate): Project {
  return { format: 'droptoapp/v1', root: importApp(t.code).root };
}

/** The R functions a template's UI uses, for the "components" list on its page. */
export function templateFunctions(t: AppTemplate): string[] {
  const names = new Set<string>();
  const root: UINode = importApp(t.code).root;
  walk(root, (n) => {
    const def = COMPONENTS[n.type];
    if (n.type === 'page') names.add(String(n.props.layout));
    else if (n.type === 'heading') names.add(String(n.props.level || 'h3'));
    else if (n.type === 'paragraph') names.add('p');
    else if (n.type === 'divider') names.add('hr');
    else if (n.type === 'tooltip') names.add('tooltip');
    else if (def.rFn && n.type !== 'cell') names.add(def.rFn);
  });
  return [...names].map((n) => `${n}()`);
}
