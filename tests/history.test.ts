import { test } from 'node:test';
import assert from 'node:assert/strict';
import { generateApp } from '../src/model/codegen';
import { emptyProject } from '../src/model/templates';
import { initialState, reducer } from '../src/state/store';
import type { EditorState } from '../src/state/store';

/** A hand-written app with formatting and comments the code generator would not reproduce. */
const HANDWRITTEN = `library(shiny)
library(bslib)

# Cars, but only the light ones
cars <- subset(mtcars, wt < 3.5)

ui <- page_sidebar(
  title = "Light cars",
  sidebar = sidebar(
    # how many rows to show
    sliderInput("rows", "Rows",   min = 1, max = 20, value = 5)
  ),
  card(card_header("Table"), tableOutput("tbl"))   # the table
)

server <- function(input, output, session) {
  output$tbl <- renderTable({
    head(cars, input$rows)  # first rows
  })
}

shinyApp(ui, server)
`;

const open = (code: string): EditorState => reducer(initialState(emptyProject()), { type: 'load', project: { ...emptyProject(), code } });

test('import, visual edit, Undo: the hand-written app.R comes back byte for byte; Redo re-applies the edit', () => {
  const opened = open(HANDWRITTEN);
  assert.equal(opened.codeDraft, HANDWRITTEN);
  const edited = reducer(opened, { type: 'updateProps', id: opened.root.id, patch: { title: 'Heavy cars' } });
  assert.equal(edited.codeDraft, null, 'a visual edit regenerates the code');
  assert.match(generateApp(edited.root).app, /title = "Heavy cars"/);

  const undone = reducer(edited, { type: 'undo' });
  assert.equal(undone.codeDraft, HANDWRITTEN);
  assert.equal(undone.root, opened.root);
  assert.equal(undone.codeError, null);

  const redone = reducer(undone, { type: 'redo' });
  assert.equal(redone.codeDraft, null);
  assert.equal(redone.root, edited.root);
  assert.equal(reducer(redone, { type: 'undo' }).codeDraft, HANDWRITTEN, 'and back again');
});

test('code-only edits (like a comment) are undo steps, typing collapses into one', () => {
  const opened = open(HANDWRITTEN);
  let s = opened;
  // A comment inside the UI: kept in app.R, not part of the design
  const at = HANDWRITTEN.indexOf('    # how many rows');
  const comment = '    # a note\n';
  const withComment = (n: number) => HANDWRITTEN.slice(0, at) + comment.slice(0, n) + HANDWRITTEN.slice(at);
  for (let i = 1; i <= comment.length; i++) s = reducer(s, { type: 'setCode', code: withComment(i) });
  assert.equal(s.root, opened.root, 'a comment does not change the design');
  assert.equal(s.past.length, opened.past.length + 1, 'one undo step for the whole comment');
  const undone = reducer(s, { type: 'undo' });
  assert.equal(undone.codeDraft, HANDWRITTEN);
  assert.equal(reducer(undone, { type: 'redo' }).codeDraft, withComment(comment.length));
});

test('Reformat (discarding hand-written code) can be undone', () => {
  const opened = open(HANDWRITTEN);
  const reformatted = reducer(opened, { type: 'discardCode' });
  assert.equal(reformatted.codeDraft, null);
  assert.equal(reducer(reformatted, { type: 'undo' }).codeDraft, HANDWRITTEN);
  // Discarding when there is nothing to discard is not an undo step
  assert.equal(reducer(reformatted, { type: 'discardCode' }), reformatted);
});

test('an invalid draft is restored exactly, error included, after Discard and Undo', () => {
  const opened = open(HANDWRITTEN);
  const broken = HANDWRITTEN + '\nnew_helper <- function(x) {\n';
  const locked = reducer(opened, { type: 'setCode', code: broken });
  assert.ok(locked.codeError);
  const discarded = reducer(locked, { type: 'discardCode' });
  assert.equal(discarded.codeError, null);
  assert.equal(discarded.root, opened.root, 'the last valid design');
  const back = reducer(discarded, { type: 'undo' });
  assert.equal(back.codeDraft, broken);
  assert.deepEqual(back.codeError, locked.codeError);
  // Still protected: visual edits are refused until it is fixed or discarded again
  assert.equal(reducer(back, { type: 'updateProps', id: back.root.id, patch: { title: 'x' } }), back);
  // Undoing further back past the invalid draft reaches the opened file
  const fixed = reducer(back, { type: 'setCode', code: HANDWRITTEN });
  assert.equal(fixed.codeError, null);
  assert.equal(reducer(fixed, { type: 'undo' }).codeDraft, broken, 'the fix is an undo step too');
});

test('a series of mixed edits undoes and redoes in order', () => {
  let s = open(HANDWRITTEN);
  const states: EditorState[] = [s];
  s = reducer(s, { type: 'setCode', code: HANDWRITTEN.replace('"Light cars"', '"Small cars"') });
  states.push(s);
  s = reducer(s, { type: 'updateProps', id: s.root.id, patch: { theme: 'flatly' } });
  states.push(s);
  s = reducer(s, { type: 'setCode', code: generateApp(s.root).app.replace('# Generated by DropToApp\n', '# mine\n') });
  states.push(s);
  for (let i = states.length - 2; i >= 0; i--) {
    s = reducer(s, { type: 'undo' });
    assert.equal(s.codeDraft, states[i].codeDraft, `undo to step ${i}`);
    assert.equal(s.root, states[i].root);
  }
  for (let i = 1; i < states.length; i++) {
    s = reducer(s, { type: 'redo' });
    assert.equal(s.codeDraft, states[i].codeDraft, `redo to step ${i}`);
  }
});
