const main = (root: UINode) => root.children.find((c) => c.type === 'main')!;
const sidebar = (root: UINode) => root.children.find((c) => c.type === 'sidebar')!;
const navbar = (root: UINode) => root.children.find((c) => c.type === 'navbar')!;

/** Read code into a design; regenerating it must be stable (code -> design -> code -> design -> same code). */
function stable(code: string) {
  const root = importApp(code).root;
  const once = generateApp(root).app;
  assert.equal(generateApp(importApp(once).root).app, once);
  return root;
}

const app = (ui: string, server = '') =>
  `# Generated by DropToApp\nlibrary(shiny)\nlibrary(bslib)\n\n${ui}\n\nserver <- function(input, output, session) {\n${server}${server ? '\n' : ''}}\n\nshinyApp(ui, server)\n`;

test('new components generate the R a person would write', () => {
  let root = emptyProject().root;
  const add = (type: Parameters<typeof createNode>[0], parent = main(root).id) => {
    const n = createNode(type, root);
    root = insertNode(root, parent, 999, n);
    return n;
  };
  add('fileInput', sidebar(root).id);
  add('conditionalPanel');
  add('accordion');
  add('tooltip');
  add('DTOutput');
  add('plotlyOutput');
  add('downloadButton');
  const { ui, server } = generateApp(root);
  assert.equal(
    ui,
    `ui <- page_sidebar(
  title = "My Shiny app",
  sidebar = sidebar(fileInput("file1", "Upload a file", accept = ".csv")),
  conditionalPanel("input.show_more == true"),
  accordion(accordion_panel("Section 1"), accordion_panel("Section 2")),
  tooltip(p("Hover over me"), "More information"),
  DT::DTOutput("dt1"),
  plotly::plotlyOutput("plotly1"),
  downloadButton("download1")
)`,
  );
  assert.equal(
    server,
    `server <- function(input, output, session) {
  # Inputs: input$file1

  output$dt1 <- DT::renderDT({
    mtcars
  })

  output$plotly1 <- plotly::renderPlotly({
    plotly::plot_ly(mtcars, x = ~wt, y = ~mpg, type = "scatter", mode = "markers")
  })

  output$download1 <- downloadHandler(
    filename = "data.csv",
    content = function(file) {
      write.csv(mtcars, file, row.names = FALSE)
    }
  )
}`,
  );
  assert.deepEqual(validate(root), []);
  // ... and the whole app reads back into the same design
  assert.equal(generateApp(importApp(generateApp(root).app).root).app, generateApp(root).app);
});

test('existing code using library(DT) / library(plotly) names is recognised', () => {
  const code = `library(shiny)
library(bslib)
library(DT)
library(plotly)

ui <- page_fluid(
  DTOutput("table"),
  plotlyOutput("chart", height = "300px"),
  DT::dataTableOutput("old")
)

server <- function(input, output, session) {
  output$table <- renderDT({
    iris
  })
  output$chart <- renderPlotly(plot_ly(iris, x = ~Sepal.Length))
  output$old <- DT::renderDataTable(head(iris))
}

shinyApp(ui, server)
`;
  const root = importApp(code).root;
  const [table, chart, old] = main(root).children;
  assert.deepEqual([table.type, chart.type, old.type], ['DTOutput', 'plotlyOutput', 'DTOutput']);
  assert.equal(table.props.code, 'iris');
  assert.equal(chart.props.code, 'plot_ly(iris, x = ~Sepal.Length)');
  assert.equal(chart.props.height, '300px');
  assert.equal(old.props.code, 'head(iris)');
  assert.equal(root.props.serverCode, '', 'all render code was matched to its output');
  assert.equal(root.props.setup, 'library(DT)\nlibrary(plotly)');
  // Regenerated with explicit namespaces (works with or without library())
  const out = generateApp(root).app;
  assert.match(out, /DT::DTOutput\("table"\)/);
  assert.match(out, /output\$chart <- plotly::renderPlotly\(\{/);
  assert.equal(generateApp(importApp(out).root).app, out);
});

test('download buttons: downloadHandler() is read back, other forms stay as server code', () => {
  const root = stable(
    app(
      `ui <- page_fluid(
  downloadButton("get", "Get the data")
)`,
      `  output$get <- downloadHandler(
    filename = "cars.csv",
    content = function(file) {
      write.csv(mtcars, file)
    }
  )`,
    ),
  );
  const btn = main(root).children[0];
  assert.equal(btn.type, 'downloadButton');
  assert.deepEqual([btn.props.label, btn.props.filename, btn.props.code], ['Get the data', 'cars.csv', 'write.csv(mtcars, file)']);

  // A file name computed by a function can't be shown as a field: the handler is kept as written
  const dynamic = `ui <- page_fluid(downloadButton("get"))
server <- function(input, output, session) {
  output$get <- downloadHandler(
    filename = function() paste0("data-", Sys.Date(), ".csv"),
    content = function(file) write.csv(mtcars, file)
  )
}
shinyApp(ui, server)`;
  const r2 = importApp(dynamic).root;
  const b2 = main(r2).children[0];
  assert.equal(b2.props.code, '');
  assert.match(String(r2.props.serverCode), /filename = function\(\) paste0/);
  assert.deepEqual(validate(r2).filter((i) => i.nodeId === b2.id), [], 'no "missing server code" warning');
  assert.equal(b2.props.label, 'Download', "R's default label");
  assert.match(generateApp(r2).app, /downloadButton\("get"\)/);
});

test('tooltips wrap exactly one component', () => {
  const root = stable(
    app(`ui <- page_fluid(
  tooltip(actionButton("go", "Go"), "Runs the analysis", placement = "right"),
  tooltip(bsicons::bs_icon("info-circle"), "Help text")
)`),
  );
  const [t1, t2] = main(root).children;
  assert.equal(t1.type, 'tooltip');
  assert.deepEqual([t1.props.text, t1.props.placement], ['Runs the analysis', 'right']);
  assert.equal(t1.children[0].type, 'actionButton');
  assert.equal(t2.children[0].type, 'rcode');

  // Unusual forms are kept as R code
  const odd = importApp(app('ui <- page_fluid(\n  tooltip(span("x"), "Part 1", "part 2")\n)')).root;
  assert.equal(main(odd).children[0].type, 'rcode');

  // A tooltip takes one component: a second one can't be dropped or moved into it
  let r = root;
  const before = r;
  r = insertNode(r, t1.id, 1, createNode('textOutput', r));
  assert.equal(r, before, 'insert refused');
  r = moveNode(r, t2.children[0].id, t1.id, 0);
  assert.equal(r, before, 'move refused');
  // Clicking a palette item with the tooltip selected puts it after the tooltip instead
  assert.deepEqual(clickAddTarget(root, t1.id, 'textOutput'), { parentId: main(root).id, index: 1 });
  // An empty tooltip still generates valid R, with a warning
  const empty = { ...t1, children: [] };
  assert.match(generateUI({ ...root, children: [sidebar(root), { ...main(root), children: [empty] }] }), /tooltip\(span\("Hover me"\), "Runs the analysis"/);
});

test('accordions: panels are wrapped, numbered and placed like tabs', () => {
  let s = initialState(emptyProject());
  const mainId = main(s.root).id;
  // An Accordion panel dropped in the main area starts a new accordion
  s = reducer(s, { type: 'add', componentType: 'accordion_panel', parentId: mainId, index: 0 });
  const acc = main(s.root).children[0];
  assert.equal(acc.type, 'accordion');
  assert.equal(acc.children[0].props.title, 'Section 1');
  // Clicking "Accordion panel" while a section is selected adds the next one after it
  s = reducer(s, { type: 'select', id: acc.children[0].id });
  const t = clickAddTarget(s.root, s.selectedId, 'accordion_panel')!;
  assert.deepEqual(t, { parentId: acc.id, index: 1 });
  s = reducer(s, { type: 'add', componentType: 'accordion_panel', ...t });
  assert.deepEqual(
    findNode(s.root, acc.id)!.children.map((c) => c.props.title),
    ['Section 1', 'Section 2'],
  );
  s = reducer(s, { type: 'updateProps', id: acc.id, patch: { multiple: false } });
  assert.match(generateUI(s.root), /accordion\(\n {4}multiple = FALSE,\n {4}accordion_panel\("Section 1"\),\n {4}accordion_panel\("Section 2"\)\n {2}\)/);
  stable(generateApp(s.root).app);
});

test('conditional panels: JavaScript condition, with a hint for R syntax', () => {
  let root = emptyProject().root;
  const cp = createNode('conditionalPanel', root);
  root = insertNode(root, main(root).id, 0, cp);
  const set = (condition: string) => ({ ...root, children: [sidebar(root), { ...main(root), children: [{ ...cp, props: { condition } }] }] });
  assert.deepEqual(validate(set("input.type == 'a'")), []);
  assert.match(validate(set('input$type == "a"'))[0].message, /input\.id instead of input\$id/);
  assert.equal(validate(set(''))[0].severity, 'error');
  const back = stable(app(`ui <- page_fluid(\n  conditionalPanel(\n    "input.more == true",\n    textInput("extra", "Extra")\n  )\n)`));
  assert.equal(main(back).children[0].children[0].type, 'textInput');
});

test('page_navbar: pages in a navigation bar, optional shared sidebar', () => {
  const code = app(
    `ui <- page_navbar(
  title = "Explorer",
  sidebar = sidebar(
    selectInput("ds", "Dataset", choices = c("iris", "mtcars"))
  ),
  nav_panel(
    "Plot",
    plotOutput("p")
  ),
  nav_panel(
    "Data",
    tableOutput("t")
  ),
  nav_spacer(),
  nav_item(a("Help", href = "https://shiny.posit.co"))
)`,
    `  # Inputs: input$ds

  output$p <- renderPlot({
    plot(get(input$ds))
  })

  output$t <- renderTable({
    head(get(input$ds))
  })`,
  );
  const root = stable(code);
  assert.equal(root.props.layout, 'page_navbar');
  assert.deepEqual(
    navbar(root).children.map((c) => c.type),
    ['nav_panel', 'nav_panel', 'rcode', 'rcode'],
  );
  assert.equal(sidebar(root).children[0].type, 'selectInput');
  assert.deepEqual(validate(root), []);

  // Without sidebar content, page_navbar has no sidebar (and its inputs are not listed)
  const noSidebar = stable(app('ui <- page_navbar(\n  title = "A",\n  nav_panel("One")\n)'));
  assert.equal(sidebar(noSidebar).children.length, 0);
});

test('switching to page_navbar and back keeps all content', () => {
  let s = initialState(emptyProject());
  const mainId = main(s.root).id;
  s = reducer(s, { type: 'add', componentType: 'plotOutput', parentId: mainId, index: 0 });
  const plotId = s.selectedId!;
  s = reducer(s, { type: 'updateProps', id: s.root.id, patch: { layout: 'page_navbar' } });
  const pages = navbar(s.root);
  assert.equal(s.root.children.some((c) => c.type === 'main'), false);
  assert.equal(pages.children[0].props.title, 'Page 1');
  assert.equal(pages.children[0].children[0].id, plotId, 'the plot moved to the first page');
  assert.equal(s.selectedId, plotId, 'selection kept');
  assert.equal(generateUI(s.root), 'ui <- page_navbar(\n  title = "My Shiny app",\n  nav_panel("Page 1", plotOutput("plot1"))\n)');

  // Clicking "Tab panel" with nothing selected adds a page
  s = reducer(s, { type: 'select', id: null });
  s = reducer(s, { type: 'add', componentType: 'nav_panel', ...clickAddTarget(s.root, null, 'nav_panel')! });
  assert.deepEqual(navbar(s.root).children.map((c) => c.props.title), ['Page 1', 'Page 2']);
  // Components clicked with nothing selected go to the first page
  assert.deepEqual(clickAddTarget(s.root, null, 'textOutput'), { parentId: navbar(s.root).children[0].id, index: 1 });

  // Back to page_sidebar: several pages become a tabset in the main area
  s = reducer(s, { type: 'updateProps', id: s.root.id, patch: { layout: 'page_sidebar' } });
  const tabs = main(s.root).children[0];
  assert.equal(tabs.type, 'navset_card_tab');
  assert.deepEqual(tabs.children.map((c) => c.props.title), ['Page 1', 'Page 2']);
  assert.equal(tabs.children[0].children[0].id, plotId);

  // Undo goes back to page_navbar in one step
  s = reducer(s, { type: 'undo' });
  assert.equal(s.root.props.layout, 'page_navbar');
  assert.equal(navbar(s.root).children.length, 2);

  // A single page becomes the main area directly
  let one = initialState(emptyProject());
  one = reducer(one, { type: 'add', componentType: 'textOutput', parentId: main(one.root).id, index: 0 });
  one = reducer(one, { type: 'updateProps', id: one.root.id, patch: { layout: 'page_navbar' } });
  one = reducer(one, { type: 'updateProps', id: one.root.id, patch: { layout: 'page_fluid' } });
  assert.equal(main(one.root).children[0].type, 'textOutput');
});
